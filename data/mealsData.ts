// Helper functions for filtering meals
export const filterMealsByCuisine = (meals: Meal[], cuisine: string): Meal[] => {
  return meals.filter(meal => meal.cuisine === cuisine);
};

export const filterMealsByDiet = (meals: Meal[], dietType: string): Meal[] => {
  return meals.filter(meal => meal.dietType === dietType);
};

export const filterMealsByCookingTime = (meals: Meal[], cookingTime: string): Meal[] => {
  return meals.filter(meal => meal.cookingTime === cookingTime);
};

export const filterMealsBySpiceLevel = (meals: Meal[], spiceLevel: string): Meal[] => {
  return meals.filter(meal => meal.spiceLevel === spiceLevel);
};

export const filterMealsByCalories = (meals: Meal[], maxCalories: number): Meal[] => {
  return meals.filter(meal => meal.calories <= maxCalories);
};

export const searchMeals = (meals: Meal[], query: string): Meal[] => {
  const lowercaseQuery = query.toLowerCase();
  return meals.filter(meal => 
    meal.name.toLowerCase().includes(lowercaseQuery) ||
    meal.description.toLowerCase().includes(lowercaseQuery) ||
    meal.tags.some(tag => tag.toLowerCase().includes(lowercaseQuery))
  );
};

// Get meals based on user preferences
export const getPersonalizedMeals = (
  meals: Meal[], 
  userPreferences: {
    cuisinePreferences?: string[];
    dietType?: string;
    cookingTime?: string;
    spiceLevel?: string;
    allergies?: string[];
  }
): Meal[] => {
  let filteredMeals = [...meals];

  // Filter by diet type
  if (userPreferences.dietType) {
    filteredMeals = filterMealsByDiet(filteredMeals, userPreferences.dietType);
  }

  // Filter by cooking time preference
  if (userPreferences.cookingTime) {
    filteredMeals = filterMealsByCookingTime(filteredMeals, userPreferences.cookingTime);
  }

  // Filter by spice level
  if (userPreferences.spiceLevel) {
    filteredMeals = filterMealsBySpiceLevel(filteredMeals, userPreferences.spiceLevel);
  }

  // Filter by cuisine preferences
  if (userPreferences.cuisinePreferences && userPreferences.cuisinePreferences.length > 0) {
    filteredMeals = filteredMeals.filter(meal => 
      userPreferences.cuisinePreferences!.includes(meal.cuisine)
    );
  }

  // Filter out meals with allergens
  if (userPreferences.allergies && userPreferences.allergies.length > 0) {
    filteredMeals = filteredMeals.filter(meal => 
      !meal.allergens.some(allergen => 
        userPreferences.allergies!.includes(allergen)
      )
    );
  }

  return filteredMeals;
}; 